import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { neon } from '@neondatabase/serverless';
import { createApp, defaultConfig } from '../server/index.js';
import { renderLayout } from '../server/layout.js';

test('Neon: beide Kaufwege, Druckdateien und gespeicherte Kontodaten überleben neue Serverinstanzen', { skip: process.env.RUN_POSTGRES_TESTS !== '1' }, async t => {
  assert.ok(process.env.DATABASE_URL, 'Neon-Test benötigt die lokal geschützte Konfiguration');
  const schema = 'archenlicht_smoke_' + randomUUID().replaceAll('-', '');
  const errors = [];
  const config = { ...defaultConfig(), storageMode: 'postgres', databaseSchema: schema, adminPassword: 'Nur-Test-Admin-2026!', serverless: true, autoShip: false, baseUrl: 'http://localhost:3000', onError: error => { if (!error.status) errors.push({ code: error.code, message: error.message }); } };
  let app, base;
  const start = async () => { app = await createApp(config); await new Promise(r => app.server.listen(0, '127.0.0.1', r)); base = `http://127.0.0.1:${app.server.address().port}`; };
  const stop = async () => { if (app) { await new Promise(r => app.server.close(r)); await app.shop.close(); app = null; } };
  const client = () => {
    let cookie = '', csrf = '';
    return async (path, method = 'GET', body) => {
      const response = await fetch(base + path, { method, headers: { Cookie: cookie, ...(body !== undefined ? { 'Content-Type': 'application/json', 'X-CSRF-Token': csrf } : {}) }, ...(body !== undefined ? { body: JSON.stringify(body) } : {}) });
      if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
      const data = response.headers.get('content-type')?.includes('json') ? await response.json() : Buffer.from(await response.arrayBuffer());
      if (data?.csrf) csrf = data.csrf;
      return { status: response.status, data };
    };
  };
  t.after(async () => {
    await stop();
    assert.match(schema, /^archenlicht_smoke_[a-f0-9]{32}$/);
    await neon(config.databaseUrl).query(`DROP SCHEMA "${schema}" CASCADE`);
  });
  await start();
  const guest = client(), stranger = client(), account = client();
  assert.equal((await guest('/api/bootstrap')).data.models.length, 74);
  await stranger('/api/bootstrap');
  const fixed = { kind: 'fixed', designId: 'unter-seinen-fluegeln', modelId: 'iphone-18-pro' };
  const custom = { kind: 'custom', designId: 'getragen', modelId: 'google-pixel-11-pro-xl', verseId: 'jes41-10', dedication: 'Für Änne · 2026' };
  assert.equal((await guest('/api/cart', 'POST', fixed)).status, 200);
  const cart = await guest('/api/cart', 'POST', custom); assert.equal(cart.data.length, 2);
  const print = cart.data[1];
  const svg = await guest(print.svgUrl); assert.equal(svg.data.toString(), renderLayout(custom).svg);
  const png = await guest(print.pngUrl); assert.equal(png.status, 200);
  const stored = await app.shop.s.get('SELECT svg FROM assets WHERE hash=?', print.hash);
  assert.match(stored.svg, /artwork-sha256:/); assert.ok(stored.svg.length < svg.data.length / 3);
  await guest('/api/advisor', 'POST', { situation: 'PRIVATE-SMOKE-SITUATION Mut' });
  await stop(); await start();
  assert.equal((await guest('/api/cart')).data.length, 2);
  assert.equal((await guest('/api/advisor')).data.situation, '');
  assert.deepEqual((await guest(print.pngUrl)).data, png.data);
  const recipient = { name: 'Mara Mustermann', email: 'mara@example.test', phone: '+4915112345678', street: 'Testweg 12', postalCode: '10115', city: 'Berlin', country: 'DE' };
  const checkout = await guest('/api/checkout', 'POST', { recipient, method: 'paypal' }); assert.equal(checkout.status, 201);
  const id = checkout.data.orderId;
  assert.equal((await stranger(`/api/orders/${id}`)).status, 404);
  assert.equal((await guest(`/api/orders/${id}/confirm`, 'POST', {})).status, 200);
  await guest(`/api/orders/${id}/confirm`, 'POST', {});
  assert.equal((await app.shop.s.get('SELECT COUNT(*) AS n FROM provider_orders WHERE external_id=?', id)).n, 1);
  await app.shop.podbase.advance(id);
  assert.equal((await guest(`/api/orders/${id}`)).data.status, 'shipped');
  await account('/api/bootstrap');
  const auth = await account('/api/auth/register', 'POST', { email: 'anna@example.test', password: 'Nur-Test-Anna-2026!' }); assert.equal(auth.status, 200);
  await account('/api/cart', 'POST', fixed);
  const second = await account('/api/checkout', 'POST', { recipient, method: 'card', saveAddress: true }); assert.equal(second.status, 201, JSON.stringify(errors));
  const confirmed = await account(`/api/orders/${second.data.orderId}/confirm`, 'POST', { saveCard: true }); assert.equal(confirmed.status, 200);
  await stop(); await start();
  assert.deepEqual((await account('/api/bootstrap')).data.account.address, recipient);
  const cards = await account('/api/account/payment-methods'); assert.equal(cards.data[0].last4, '4242'); assert.ok(cards.data[0].expMonth);
  const history = await account('/api/account/orders'); assert.equal(history.data.length, 1);
  const rows = await app.shop.s.all('SELECT configuration,print_text,svg FROM assets');
  assert.equal(JSON.stringify(rows).includes('PRIVATE-SMOKE-SITUATION'), false);
});
